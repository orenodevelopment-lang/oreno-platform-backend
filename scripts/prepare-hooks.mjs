import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';

/**
 * Install the repository's Git hooks.
 *
 * Runs from `npm install` via the `prepare` script. It is deliberately
 * conservative: it skips silently when there is no Git repository (a packaged
 * tarball, a CI checkout with a shallow clone, a Docker build), and it refuses
 * to overwrite a hook it did not write, so a contributor's own hook survives.
 */
const MARKER = 'generated by scripts/prepare-hooks.mjs';

const HOOK = `#!/bin/sh
# ${MARKER} — do not edit; edit the template there and re-run "npm install".
#
# Keeps the two checks that are cheap to run and expensive to notice: a failing
# typecheck or lint should not reach CI.
set -e
npm run --silent typecheck
npm run --silent lint
`;

function gitDir() {
  try {
    return execFileSync('git', ['rev-parse', '--git-dir'], {
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim();
  } catch {
    return undefined;
  }
}

function main() {
  if (process.env['CI']) return;
  if (process.env['ORENO_SKIP_HOOKS']) return;

  const dir = gitDir();
  if (!dir) return;

  const hooksDir = resolve(process.cwd(), dir, 'hooks');
  const hookPath = resolve(hooksDir, 'pre-commit');

  if (existsSync(hookPath)) {
    const current = readFileSync(hookPath, 'utf8');
    if (!current.includes(MARKER)) {
      console.log('prepare-hooks: an existing pre-commit hook was left untouched.');
      return;
    }
  }

  mkdirSync(dirname(hookPath), { recursive: true });
  writeFileSync(hookPath, HOOK, { encoding: 'utf8', mode: 0o755 });
  try {
    chmodSync(hookPath, 0o755);
  } catch {
    // Windows does not carry a POSIX mode; Git for Windows ignores it.
  }

  console.log('prepare-hooks: installed the pre-commit hook.');
}

main();
