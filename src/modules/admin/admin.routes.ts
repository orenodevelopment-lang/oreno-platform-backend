import { Router } from 'express';
import { asyncHandler } from '../../common/http/async-handler.js';
import { authenticate } from '../auth/index.js';
import * as c from './admin.controller.js';
export function createAdminRouter() {
  const r = Router();
  r.use(authenticate());
  r.get('/users', asyncHandler(c.users));
  r.get('/users/:id', asyncHandler(c.userDetail));
  r.post('/users/:id/status', asyncHandler(c.userStatus));
  r.post('/users/:id/sessions/revoke', asyncHandler(c.revokeUserSessions));
  r.get('/organisations', asyncHandler(c.organisations));
  r.get('/organisations/:id', asyncHandler(c.organisationDetail));
  r.post('/organisations/:id/status', asyncHandler(c.organisationStatus));
  r.post('/organisations/:id/verification', asyncHandler(c.organisationVerification));
  r.get('/applications', asyncHandler(c.applicationReviews));
  r.get('/placements', asyncHandler(c.placementReviews));
  r.get('/jobs', asyncHandler(c.jobs));
  r.get('/compensation/payroll', asyncHandler(c.payrollReviews));
  r.get('/compensation/payments', asyncHandler(c.paymentReviews));
  r.post('/jobs/:id/moderation', asyncHandler(c.moderate));
  r.get('/roles', asyncHandler(c.roles));
  r.post('/roles/grant', asyncHandler(c.grantRole));
  r.post('/roles/revoke', asyncHandler(c.revokeRole));
  r.get('/leads/:kind', asyncHandler(c.leads));
  r.patch('/leads/:kind/:id', asyncHandler(c.leadUpdate));
  r.get('/audit', asyncHandler(c.audit));
  r.get('/configuration', asyncHandler(c.configuration));
  r.put('/configuration/feature-flags', asyncHandler(c.flag));
  r.put('/configuration/policies', asyncHandler(c.policy));
  r.post('/announcements', asyncHandler(c.announcement));
  r.get('/announcements', asyncHandler(c.announcements));
  r.get('/deliveries', asyncHandler(c.deliveries));
  r.post('/deliveries/:id/retry', asyncHandler(c.retryDelivery));
  r.get('/operations', asyncHandler(c.operations));
  r.post('/operations/jobs/:id/retry', asyncHandler(c.retry));
  return r;
}
